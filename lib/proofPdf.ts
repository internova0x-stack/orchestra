import { PDFDocument, StandardFonts, degrees, rgb } from "pdf-lib";
import type { ProofDoc } from "./tools.ts";

// The downloadable payment confirmation: the proof card's fields on one A4 page, under a
// "Simulated document" watermark. No institution's name or logo appears on it.

/** The standard PDF fonts can't draw the naira sign; spell the currency out instead. */
const safe = (s: string) => s.replace(/₦/g, "NGN ");

export async function proofPdf(p: ProofDoc): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`Payment confirmation ${p.reference}`);
  doc.setProducer("Orchestra AI prototype");
  const page = doc.addPage([595.28, 841.89]); // A4
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.08, 0.09, 0.17);
  const grey = rgb(0.36, 0.38, 0.45);
  const indigo = rgb(0.26, 0.22, 0.79);

  // Watermark across the page.
  page.drawText("SIMULATED DOCUMENT", {
    x: 95, y: 260, size: 54, font: bold, color: rgb(0.85, 0.86, 0.92), rotate: degrees(40), opacity: 0.6,
  });

  page.drawRectangle({ x: 0, y: 811.89, width: 595.28, height: 30, color: indigo });
  page.drawText("Prototype - simulated data. Not a real payment record.", { x: 48, y: 822, size: 10, font: bold, color: rgb(1, 1, 1) });

  page.drawText("Payment confirmation", { x: 48, y: 750, size: 26, font: bold, color: ink });
  page.drawText(`Confirmation ${p.reference}  ·  Issued ${p.issued} (Lagos time)`, { x: 48, y: 726, size: 10, font, color: grey });

  page.drawText(safe(p.amount), { x: 48, y: 672, size: 32, font: bold, color: ink });
  page.drawText("Delivered to the recipient", { x: 48, y: 652, size: 11, font, color: grey });

  const rows: [string, string][] = [
    ["Recipient", p.recipient],
    ["Account", p.account],
    ["Amount", safe(p.amount)],
    ["Currency", p.currency],
    ["Date delivered", p.date],
    ["Payout reference", p.payout],
    ["Payout route", p.route],
  ];
  let y = 600;
  for (const [label, value] of rows) {
    page.drawLine({ start: { x: 48, y: y + 22 }, end: { x: 547, y: y + 22 }, thickness: 0.5, color: rgb(0.89, 0.9, 0.94) });
    page.drawText(label, { x: 48, y, size: 11, font, color: grey });
    page.drawText(value, { x: 220, y, size: 12, font: bold, color: ink });
    y -= 40;
  }

  page.drawText("This confirmation shows that the payout above was completed. Account numbers are masked to the last four digits.", {
    x: 48, y: 290, size: 9, font, color: grey, maxWidth: 500, lineHeight: 13,
  });
  page.drawText("Generated by Orchestra AI, an AI support assistant prototype, from simulated data.", { x: 48, y: 60, size: 9, font, color: grey });

  return doc.save();
}
